const getTrackerFilterData = (tracker) => {
  const isCertified = certifiedTrackerIds.has(tracker.id)
  const tasks = [rnisTask, advantumTask, baseTask]

  if (tracker.connections?.includes('CAN')) {
    tasks.push(fuelControlTask)
  }

  if (cigaretteLighterTrackerIds.has(tracker.id)) {
    tasks.push(cigaretteLighterTask)
  }

  if (isCertified) {
    tasks.push(regulationTask)
  }

  return {
    isCertified,
    vehicleTypes: isCertified ? certifiedVehicleTypes : commonVehicleTypes,
    tasks,
  }
}

