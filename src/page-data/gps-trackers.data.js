const getTrackerPopularityIndex = (tracker) => {
  const index = trackerPopularityOrder.findIndex((idPrefix) =>
    tracker.id.startsWith(idPrefix)
  )

  return index === -1 ? trackerPopularityOrder.length : index
}

const sortTrackersByPopularity = (trackers) =>
  [...trackers].sort(
    (firstTracker, secondTracker) =>
      getTrackerPopularityIndex(firstTracker) -
      getTrackerPopularityIndex(secondTracker)
  )

