const createGalileoskyTracker = (model) => {
  const connection = model.lte ? '4G LTE' : model.connection || '2G'
  const antenna = model.external ? 'Внешняя' : 'Внутренняя'
  const connections = [
    ...(model.can ? ['CAN'] : []),
    ...(model.wifi ? ['Wi-Fi'] : []),
    ...(model.rs485 === false ? [] : ['RS-485']),
    ...(model.rs232 === false ? [] : ['RS-232']),
    ...(model.oneWire ? ['1-Wire'] : []),
    ...(model.bluetooth === false
      ? []
      : [model.ble ? 'Bluetooth 5.0 / BLE' : 'Bluetooth']),
    'DI/DO',
  ]

  return createTracker({
    id: `galileosky-${model.slug}`,
    title: `Galileosky ${model.title}`,
    manufacturer: 'Galileosky',
    photoGroup: model.photoGroup,
    image: model.image || trackerPhotoGroups[model.photoGroup] || Galileosky10,
    description:
      model.description ||
      'Терминал Galileosky для транспортной телематики и подключения периферии',
    connections,
    gpsAntenna: antenna,
    bluetooth:
      model.bluetooth === false ? 'Нет' : model.ble ? '5.0 / BLE' : 'Есть',
    voltage: '9–39 В постоянного тока',
    battery: model.battery || 'Встроенный резервный аккумулятор 600 мА·ч',
    input: model.input || 'Дискретные, аналоговые, импульсные и CAN-данные',
    output: 'До 4 транзисторных выходов',
    memory:
      model.memory || 'Встроенная память, поддержка microSD по модификации',
    protection: model.protection || 'IP54 по модификации',
    sizes: model.sizes || '',
    weight: model.weight || '',
    country: 'Россия',
    connection,
    simCount: model.simCount || 2,
    details: model.details,
  })
}

